// Writes marketing/privacidade.html from constants/privacyPolicy.ts, so the
// site and the app show the same policy. Run: bun scripts/privacy-page.ts
import { writeFileSync } from 'node:fs';
import { PRIVACY_POLICY, PRIVACY_POLICY_UPDATED } from '../constants/privacyPolicy';

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const sections = PRIVACY_POLICY.map(
  (s) => `      <section>
        <h2>${esc(s.title)}</h2>
${s.body.map((p) => `        <p>${esc(p)}</p>`).join('\n')}
      </section>`,
).join('\n');

const html = `<!doctype html>
<html lang="pt-PT">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>Política de privacidade · Wysta</title>
  <meta name="description" content="Política de privacidade da Wysta, projeto académico de saúde sexual e reprodutiva.">
  <meta name="theme-color" content="#FBF7F4">
  <link rel="icon" href="/logo-mark.svg" type="image/svg+xml">
  <link rel="stylesheet" href="styles.css">
</head>
<body>
  <!-- Generated by scripts/privacy-page.ts from constants/privacyPolicy.ts. Do not edit by hand. -->
  <div class="academic-bar" role="note">
    <span><strong>Projeto académico</strong> · não é um serviço de saúde real.</span>
  </div>
  <header class="nav">
    <a class="brand" href="/" aria-label="Wysta">
      <img class="brand-mark" src="/logo-mark.svg" alt="" width="30" height="30">
      <span class="brand-name">Wysta</span>
    </a>
  </header>
  <main class="policy">
    <article>
      <h1>Política de privacidade</h1>
      <p class="policy-updated">Atualizada a ${esc(PRIVACY_POLICY_UPDATED)}</p>
${sections}
    </article>
  </main>
</body>
</html>
`;
writeFileSync(new URL('../marketing/privacidade.html', import.meta.url), html);
console.log('marketing/privacidade.html written');
